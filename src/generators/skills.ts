/* ──────────────────────────────────────────────────────────────
 * Skill file builder — generates the markdown content
 * ────────────────────────────────────────────────────────────── */

interface SkillFileOptions {
  slug: string;
  version: string;
  framework: string;
  category: string;
  triggers: string[];
  author: string;
  status: 'active' | 'draft' | 'deprecated';
  title: string;
  whenToRead: string;
  context: string;
  steps: string[];
  patterns: string[];
  antiPatterns: string[];
  example: string;
  notes?: string;
}

function buildSkillFile(opts: SkillFileOptions): string {
  const triggersYaml = opts.triggers.map((t) => `  - "${t}"`).join('\n');
  const stepsList = opts.steps.map((s, i) => `${i + 1}. ${s}`).join('\n');
  const patternsList = opts.patterns.map((p) => `- ${p}`).join('\n');
  const antiPatternsList = opts.antiPatterns.map((p) => `- ${p}`).join('\n');
  const notesSection = opts.notes ? `\n## Notes\n${opts.notes}\n` : '';

  return `---
skill: ${opts.slug}
version: ${opts.version}
framework: ${opts.framework}
category: ${opts.category}
triggers:
${triggersYaml}
author: ${opts.author}
status: ${opts.status}
---

# Skill: ${opts.title}

## When to Read This
${opts.whenToRead}

## Context
${opts.context}

## Steps
${stepsList}

## Patterns We Use
${patternsList}

## Anti-Patterns — Never Do This
${antiPatternsList}

## Example
\`\`\`
${opts.example}
\`\`\`
${notesSection}`;
}

