function getFrameworkLabel(framework: NexusConfig['frontendFramework']): string {
  const labels: Record<string, string> = {
    nextjs: 'Next.js',
    'react-vite': 'React + Vite',
    sveltekit: 'SvelteKit',
    nuxt: 'Nuxt 3',
    astro: 'Astro',
    remix: 'Remix',
    none: 'Framework-Agnostic',
  };
  return labels[framework] ?? framework;
}

/**
 * List all skill slugs that were generated for a given framework.
 * Used by upgrade logic to know which core skill files exist.
 */
export function getCoreSkillSlugs(framework: NexusConfig['frontendFramework']): string[] {
  const shared = getSharedSkills().map((s) => s.slug);
  const fw = getFrameworkSkills(framework).map((s) => s.slug);
  return [...fw, ...shared];
}
